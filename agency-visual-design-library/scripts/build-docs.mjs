#!/usr/bin/env node
// Generates visual-styles/*.md and visual-styles/tokens.css from
// library/styles-data.js, so the Markdown specs never drift from the
// visual library. Run: node agency-visual-design-library/scripts/build-docs.mjs
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const ctx = { window: {} };
vm.runInNewContext(readFileSync(join(root, "library/styles-data.js"), "utf8"), ctx);
const styles = ctx.window.AVDL_STYLES;
const outDir = join(root, "visual-styles");
mkdirSync(outDir, { recursive: true });

const pad = (n) => String(n).padStart(2, "0");
const plain = (s) => String(s).replace(/\*/g, "");
const bullets = (items) => items.map((i) => `- ${plain(i)}`).join("\n");
const cell = (s) => plain(s ?? "").replace(/\|/g, "\\|");
const slug = (s, i) => `${pad(i + 1)}-${s.id}`;
const GENERATED = "<!-- Generated by scripts/build-docs.mjs from library/styles-data.js. Edit the data file, not this file. -->";

function styleDoc(s, i) {
  const t = s.typography;
  const fontRow = (role, f) => (f ? `| ${role} | **${cell(f.family)}** | ${cell(f.weights)} | ${cell(f.use)} |` : null);
  const so = s.social;
  const w = s.website;
  return [
    GENERATED,
    "",
    `# Style ${pad(i + 1)} · ${s.name}`,
    "",
    `> ${s.tagline}`,
    "",
    `**Keywords:** ${s.keywords.join(" · ")}  `,
    `**Sample brand in examples:** ${s.sampleBrand}${s.sampleBrandArabic ? ` (${s.sampleBrandArabic})` : ""}, ${s.sampleBrandType.toLowerCase()} (invented)`,
    "",
    "## Concept",
    "",
    s.concept,
    "",
    "## Target industries",
    "",
    bullets(s.industries),
    "",
    "## Color palette",
    "",
    "| Name | Hex | Role | Share |",
    "| --- | --- | --- | ---: |",
    ...s.palette.map((c) => `| ${c.name} | \`${c.hex}\` | ${cell(c.role)} | ${c.share}% |`),
    "",
    `**Rule:** ${s.paletteRule}`,
    "",
    "## Typography",
    "",
    "| Role | Family | Weights | Use |",
    "| --- | --- | --- | --- |",
    fontRow("Display", t.display),
    fontRow("Body", t.body),
    fontRow("Utility", t.utility),
    `| Arabic | **${cell(t.arabic.family)}** | | ${cell(t.arabic.note)} |`,
    "",
    "**Type scale** (desktop, px size / line height)",
    "",
    "| Level | Size | Weight | Detail |",
    "| --- | --- | --- | --- |",
    ...t.scale.map((r) => `| ${r.level} | ${r.size} | ${r.weight} | ${cell(r.detail)} |`),
    "",
    bullets(t.rules),
    "",
    "## Layout rules",
    "",
    `- **Grid:** ${s.layout.grid}`,
    `- **Spacing:** ${s.layout.spacing}`,
    `- **Corners:** ${s.layout.radius}`,
    "",
    bullets(s.layout.rules),
    "",
    "## Photography direction",
    "",
    s.photography.summary,
    "",
    bullets(s.photography.rules),
    "",
    "**Sample shot list**",
    "",
    s.photography.shots.map((sh, n) => `${n + 1}. ${sh.caption} (grade: \`${sh.tone.join("` → `")}\`)`).join("\n"),
    "",
    "**Avoid**",
    "",
    bullets(s.photography.avoid),
    "",
    "## Graphic elements",
    "",
    bullets(s.graphics),
    "",
    "## UI examples",
    "",
    bullets(s.ui.notes),
    "",
    `- Primary button: \`${s.ui.primary}\` · Secondary button: \`${s.ui.secondary}\``,
    `- Input: ${s.ui.inputLabel}: \`${s.ui.inputValue}\``,
    `- Tags: ${s.ui.tags.map((x) => `\`${x}\``).join(" ")}`,
    `- Card: **${s.ui.card.title}**, ${s.ui.card.meta}, ${s.ui.card.price}`,
    "",
    "## Social media examples",
    "",
    bullets(so.notes),
    "",
    "| Format | Eyebrow | Headline | CTA |",
    "| --- | --- | --- | --- |",
    `| Feed post 1080 × 1080 | ${cell(so.feed.eyebrow)} | ${cell(so.feed.headline)} | ${cell(so.feed.cta || "")} |`,
    `| Story 1080 × 1920 | ${cell(so.story.eyebrow)} | ${cell(so.story.headline)} | ${cell(so.story.cta)} |`,
    `| Feed ad 1080 × 1350 | ${cell(so.ad.eyebrow)} | ${cell(so.ad.headline)} | ${cell(so.ad.cta)} |`,
    "",
    "## Website example",
    "",
    bullets(w.notes),
    "",
    `- **Navigation:** ${w.nav.join(" · ")}`,
    `- **Hero eyebrow:** ${w.hero.eyebrow}`,
    `- **Hero headline:** ${plain(w.hero.headline)}`,
    `- **Hero copy:** ${w.hero.sub}`,
    `- **Actions:** ${w.hero.cta} / ${w.hero.cta2}`,
    `- **Proof row:** ${w.features.map((f) => `${f.title} (${f.text})`).join(" · ")}`,
    "",
    "## Do / Don't",
    "",
    "| Do | Don't |",
    "| --- | --- |",
    ...s.dos.map((d, n) => `| ${cell(d)} | ${cell(s.donts[n] || "")} |`),
    "",
    "## Design tokens",
    "",
    "```css",
    tokenBlock(s, `[data-style="${s.id}"]`),
    "```",
    "",
    `See it rendered: open \`index.html\` and go to **${s.name}** (\`#${s.id}\`).`,
    "",
  ]
    .filter((l) => l !== null)
    .join("\n");
}

function tokenBlock(s, selector) {
  const t = s.tokens;
  const map = {
    bg: t.bg, surface: t.surface, ink: t.ink, muted: t.muted, accent: t.accent, "accent-2": t.accent2,
    "on-accent": t.onAccent, line: t.line, "font-display": t.fontDisplay, "font-body": t.fontBody,
    "display-weight": t.displayWeight, "display-case": t.displayCase, "display-tracking": t.displayTracking,
    radius: t.radius, "button-radius": t.btnRadius, "border-width": t.borderWidth, shadow: t.shadow,
  };
  const lines = Object.entries(map).map(([k, v]) => `  --avdl-${k}: ${v};`);
  const pal = s.palette.map((c) => `  --avdl-color-${c.name.toLowerCase().replace(/[^a-z0-9]+/g, "-")}: ${c.hex};`);
  return `${selector} {\n${lines.join("\n")}\n${pal.join("\n")}\n}`;
}

styles.forEach((s, i) => writeFileSync(join(outDir, `${slug(s, i)}.md`), styleDoc(s, i)));

writeFileSync(
  join(outDir, "tokens.css"),
  `/* ${GENERATED.slice(5, -4)} */\n/* Usage: <div data-style="quiet-luxury"> … uses var(--avdl-accent) … */\n\n` +
    styles.map((s) => tokenBlock(s, `[data-style="${s.id}"]`)).join("\n\n") + "\n",
);

const index = [
  GENERATED,
  "",
  "# Visual styles",
  "",
  "Ten visual directions. Each file covers concept, target industries, palette, typography, layout, photography, graphic elements and UI, social and website examples.",
  "",
  "| # | Style | In one line | Best for |",
  "| --- | --- | --- | --- |",
  ...styles.map((s, i) => `| ${pad(i + 1)} | [${s.name}](./${slug(s, i)}.md) | ${s.tagline} | ${s.industries.slice(0, 3).join(", ")} |`),
  "",
  "`tokens.css` holds every style's tokens as CSS custom properties, scoped by `[data-style=\"…\"]`.",
  "",
].join("\n");
writeFileSync(join(outDir, "README.md"), index);

console.log(`Wrote ${styles.length} style docs, README.md and tokens.css to ${outDir}`);
